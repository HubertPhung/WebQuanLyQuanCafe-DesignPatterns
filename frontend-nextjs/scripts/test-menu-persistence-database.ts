import assert from 'node:assert/strict'
import pg from 'pg'
import { drizzle } from 'drizzle-orm/node-postgres'
import { MENU_IMAGE_SCHEMA_SQL } from '../lib/db/menu-image-schema'

class TestRollback extends Error {}

async function main() {
  const actualPool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 1 })
  const client = await actualPool.connect()
  try {
    // Pin the Supabase backend with BEGIN; application transactions then use SAVEPOINTs.
    // All application reads/writes share this connection and the outer transaction rolls back.
    await drizzle(client).transaction(async transaction => {
      Object.assign(globalThis, {
        adminPool: { query: client.query.bind(client) },
        drizzleDb: transaction,
      })
      await client.query(`CREATE TEMP TABLE admin_menu_items (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL, category text NOT NULL, kind text NOT NULL DEFAULT 'menu',
        unit text NOT NULL DEFAULT 'ly', cost_price numeric(10,2) NOT NULL DEFAULT 0,
        sell_price numeric(10,2) NOT NULL DEFAULT 0, in_stock boolean NOT NULL DEFAULT true,
        recipe text, image_url varchar(255), variations jsonb NOT NULL DEFAULT '[]',
        created_at timestamptz NOT NULL DEFAULT now()
      ) ON COMMIT DROP`)
      await client.query(`CREATE TEMP TABLE admin_menu_links (
        menu_item_id integer PRIMARY KEY, java_menu_id integer NOT NULL CHECK (java_menu_id > 0),
        linked_at timestamptz NOT NULL DEFAULT now()
      ) ON COMMIT DROP`)
      await client.query('CREATE TEMP TABLE admin_sync_queue (order_code text PRIMARY KEY, queued_at timestamptz DEFAULT now()) ON COMMIT DROP')
      assert.ok((await client.query("SELECT 'admin_menu_items'::regclass = (SELECT oid FROM pg_class WHERE relnamespace=pg_my_temp_schema() AND relname='admin_menu_items') AS isolated")).rows[0].isolated)
      const imageUrl = 'data:image/jpeg;base64,' + 'A'.repeat(120000)
      await client.query('SAVEPOINT legacy_image')
      await assert.rejects(client.query("INSERT INTO admin_menu_items (name,category,image_url) VALUES ('Legacy photo','Bánh ngọt',$1)", [imageUrl]), { code: '22001' })
      await client.query('ROLLBACK TO SAVEPOINT legacy_image')
      await client.query("INSERT INTO admin_menu_items (name,category,image_url) VALUES ('Existing photo','Bánh ngọt','/images/croissant.png')")
      await client.query(MENU_IMAGE_SCHEMA_SQL)
      await client.query(MENU_IMAGE_SCHEMA_SQL)
      assert.equal((await client.query("SELECT image_url FROM admin_menu_items WHERE name='Existing photo'")).rows[0].image_url, '/images/croissant.png')

      const { persistMenuItem } = await import('../lib/admin/menu-store')
      const { getMockMenuItems } = await import('../lib/db/mock-store')
      const mockCount = getMockMenuItems().length
      const input = { name: 'Bánh mới có ảnh tải lên', category: 'Bánh ngọt', kind: 'menu' as const, unit: 'phần', costPrice: 18000, sellPrice: 34000, recipe: 'Bánh mới trong ngày', imageUrl, variations: [] }
      const id = await persistMenuItem(input, 43)
      const row = (await client.query('SELECT * FROM admin_menu_items WHERE id=$1', [id])).rows[0]
      assert.equal(row.image_url, imageUrl)
      assert.equal(row.in_stock, true)
      assert.equal(Number(row.sell_price), 34000)
      assert.equal((await client.query('SELECT java_menu_id FROM admin_menu_links WHERE menu_item_id=$1', [id])).rows[0].java_menu_id, 43)
      assert.equal(await persistMenuItem(input, 43), id, 'Retry reuses the same local item')
      assert.equal((await client.query('SELECT count(*)::int AS count FROM admin_menu_items')).rows[0].count, 2)
      const { getMenuProducts, findMenuVariant, menuVariantId } = await import('../lib/storefront/menu-catalog')
      const product = (await getMenuProducts()).find(product => product.id === `gid://dalatcafe/Product/${id}`)
      assert.equal(product?.title, input.name)
      assert.equal(product?.featuredImage?.url, imageUrl)
      assert.equal(product?.variants.nodes[0].price.amount, '34000')
      assert.ok(product?.variants.nodes[0].availableForSale)
      assert.equal((await findMenuVariant(menuVariantId(id)))?.item.id, id)
      await assert.rejects(persistMenuItem({ ...input, name: 'Atomic link failure' }, -7), /Chưa lưu được món/)
      assert.equal((await client.query("SELECT count(*)::int AS count FROM admin_menu_items WHERE name='Atomic link failure'")).rows[0].count, 0)
      assert.equal(getMockMenuItems().length, mockCount, 'Database failure never writes an unrelated mock item')
      throw new TestRollback()
    })
  } catch (error) {
    if (!(error instanceof TestRollback)) throw error
    console.log('PASS: legacy uploaded-image failure reproduced; repeatable upgrade preserves images; menu and Java link save atomically; retries avoid duplicates; storefront lists and prices new food; database failure rolls back without mock fallback. Entire test rolled back.')
  } finally { client.release(); await actualPool.end() }
}

main().catch(error => { console.error(error); process.exitCode = 1 })
