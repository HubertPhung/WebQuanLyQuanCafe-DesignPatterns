import assert from 'node:assert/strict'
import { formatOrderTables } from '../lib/admin/order-display'
import { createMockOrder, getMockActiveOrders, updateMockOrderStatus, markMockOrderPaid } from '../lib/db/mock-store'
import { RESERVATION_TIME_SLOTS, hasReservationStarted } from '../lib/reservation-rules'
import { saveMockTable, createMockReservation, getMockReservations, expireMockNoShows, transferMockReservation, getMockOrdersByCode, settleMockTables, updateMockReservationStatus, updateMockTableStatus, getMockTables } from '../lib/db/mock-store'

const scheduled = new Date('2026-10-19T07:30:00+07:00')
assert.equal(hasReservationStarted(scheduled, scheduled.getTime() - 1), false)
assert.equal(hasReservationStarted(scheduled, scheduled.getTime()), true)
assert.equal(hasReservationStarted(new Date('invalid')), false)

assert.equal(RESERVATION_TIME_SLOTS.length, 31)
assert.equal(RESERVATION_TIME_SLOTS[0], '07:00')
assert.equal(RESERVATION_TIME_SLOTS.at(-1), '22:00')
const ids = [0, 1, 2].map(index => saveMockTable({ name: `Reservation test ${index}`, seats: 4, zone: 'Test groups', imageUrl: null }).id)
const date = new Date(Date.now() + 86400000).toLocaleDateString('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' })
const input = { customer: 'Group test', contact: '0901234567', email: null, note: null, dateTime: new Date(`${date}T10:00:00+07:00`), guests: 6, tableId: ids[0], tableIds: ids.slice(0, 2), preOrders: [{ name: 'Coffee', qty: 1, price: 45000 }] }
assert.equal(createMockReservation({ ...input, tableIds: [ids[0]] }).ok, false)
assert.equal(createMockReservation({ ...input, tableIds: [ids[0], ids[0]] }).ok, false)
const first = createMockReservation(input)
assert.equal(first.ok, true)
assert.doesNotThrow(() => saveMockTable({ name: 'Updated group table', seats: 4, zone: 'Test groups', imageUrl: null }, ids[0]))
assert.throws(() => saveMockTable({ name: 'Updated group table', seats: 1, zone: 'Test groups', imageUrl: null }, ids[0]), /Số chỗ/)
assert.equal(createMockReservation({ ...input, guests: 2, tableId: ids[1], tableIds: [ids[1]] }).ok, false)
assert.equal(transferMockReservation(first.code!).ok, false, 'Tomorrow\'s booking must not reach the kitchen today')
assert.equal(getMockOrdersByCode([first.code!]).length, 0)
const firstReservation = getMockReservations().find(value => value.code === first.code)!
assert.equal(firstReservation.status, 'Chờ xác nhận')
firstReservation.dateTime = new Date()
assert.equal(transferMockReservation(first.code!).ok, true)
assert.equal(updateMockReservationStatus(first.code!, 'Đã hủy').ok, false, 'Seated bookings must be handled at the POS')
const second = createMockReservation({ ...input, guests: 2, tableId: ids[2], tableIds: [ids[2]] })
assert.equal(second.ok, true)
const reservation = getMockReservations().find(value => value.code === second.code)!
const cutoff = reservation.dateTime.getTime() + 15 * 60000
expireMockNoShows(cutoff - 1)
assert.equal(reservation.status, 'Chờ xác nhận')
expireMockNoShows(cutoff)
assert.equal(reservation.status, 'Đã hủy')
assert.equal(transferMockReservation(second.code!).ok, false)
assert.equal(updateMockReservationStatus(second.code!, 'Đã đặt').ok, false, 'Cancelled bookings must not reopen')
const third = createMockReservation({ ...input, guests: 2, tableId: ids[2], tableIds: [ids[2]] })
assert.equal(third.ok, true)
assert.equal(updateMockReservationStatus(third.code!, 'Đã đặt').ok, true)
updateMockTableStatus(ids[2], 'reserved', 2)
assert.equal(updateMockReservationStatus(third.code!, 'Đã hủy').ok, true)
assert.equal(getMockTables().find(table => table.id === ids[2])!.status, 'available')
assert.equal(getMockOrdersByCode([third.code!]).length, 0)
assert.equal(createMockReservation({ ...input, guests: 2, tableId: ids[2], tableIds: [ids[2]] }).ok, true, 'Cancellation frees the booking slot')
assert.equal(getMockReservations().find(value => value.code === first.code)!.status, 'Hoàn thành', 'Seated guests must not expire')
const orders = getMockOrdersByCode([first.code!])
assert.equal(orders.length, 1)
assert.equal(orders[0].items.length, 1)
assert.throws(() => settleMockTables([ids[0]], 'cash', 1000000))
assert.throws(() => settleMockTables(ids.slice(0, 2), 'cash', 1))
assert.throws(() => settleMockTables(ids.slice(0, 2), 'cash', 1000000, 1))
assert.equal(orders[0].paymentStatus, 'unpaid')
assert.equal(settleMockTables(ids.slice(0, 2), 'cash', 1000000).orders.length, 1)
assert.throws(() => settleMockTables(ids.slice(0, 2), 'cash', 1000000))
assert.equal(formatOrderTables(orders[0]), `Bàn ${ids[0]}, Bàn ${ids[1]}`)
assert.equal(formatOrderTables({ ...orders[0], tableIds: [ids[0], ids[0]] }), `Bàn ${ids[0]}`)
assert.equal(formatOrderTables(orders[0], ids.map(id => ({ id, name: `Table ${id}` }))), `Bàn ${ids[0]}, Bàn ${ids[1]}`)
assert.equal(createMockOrder({ orderCode: 'KDS-OTHER', customer: 'Other guest', tableId: ids[0], orderType: 'dine-in', paymentMethod: 'cash', paid: false, lines: [] }).ok, true)
const otherOrder = getMockOrdersByCode(['KDS-OTHER'])[0]
assert.equal(updateMockOrderStatus(orders[0].id, 'ready').ok, true)
assert.equal(updateMockOrderStatus(orders[0].id, 'cancelled').ok, true)
assert.equal(orders[0].paymentStatus, 'refunded')
assert.equal(getMockReservations().find(value => value.code === first.code)!.status, 'Đã hủy')
assert.equal(getMockTables().find(table => table.id === ids[0])!.status, 'occupied', 'Another open ticket keeps its table occupied')
assert.equal(getMockTables().find(table => table.id === ids[1])!.status, 'cleaning', 'The other grouped table is released')
assert.equal(getMockActiveOrders().some(order => order.id === orders[0].id), false)
assert.equal(getMockOrdersByCode([first.code!]).length, 1, 'Cancelled tickets remain in history')
assert.equal(markMockOrderPaid(orders[0].id).ok, false)
assert.equal(updateMockOrderStatus(orders[0].id, 'pending').ok, false)
assert.equal(updateMockOrderStatus(orders[0].id, 'cancelled').ok, true, 'Repeated cancellation is idempotent')
assert.equal(updateMockOrderStatus(otherOrder.id, 'cancelled').ok, true)
assert.equal(otherOrder.paymentStatus, 'unpaid', 'Cancelling an unpaid ticket must not create a refund')
assert.equal(getMockTables().find(table => table.id === ids[0])!.status, 'cleaning')
assert.throws(() => settleMockTables([ids[0]], 'cash', 1000000), /không còn đơn/)
console.log('PASS: opening slots, group capacity/conflicts, scheduled POS opening, cancellation/rebooking, no-show boundary, seated protection and group payments')
